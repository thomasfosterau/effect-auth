/**
 * Regenerate `packages/effect-auth/src/plugins/ConfusablesData.ts` from
 * Unicode's UTS 39 `confusables.txt` and the UCD's `PropertyValueAliases.txt`
 * (for the script codes).
 *
 *   vpx scripts/generate-confusables.ts 18.0.0
 *
 * By default both files come from unicode.org. Where that host is out of
 * reach, pass either file as a path or another URL:
 *
 *   vpx scripts/generate-confusables.ts 18.0.0 \
 *     --confusables ./confusables.txt --aliases ./PropertyValueAliases.txt
 *
 * The generated module records the version and each file's SHA-256.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const [version, ...rest] = process.argv.slice(2);
if (version === undefined || !/^\d+\.\d+\.\d+$/.test(version)) {
  throw new TypeError(
    "Usage: generate-confusables.ts <unicode version> [--confusables <src>] [--aliases <src>]",
  );
}
const option = (name: string): string | undefined => {
  const at = rest.indexOf(`--${name}`);
  return at < 0 ? undefined : rest[at + 1];
};
const confusablesSource =
  option("confusables") ?? `https://www.unicode.org/Public/security/${version}/confusables.txt`;
const aliasesSource =
  option("aliases") ?? `https://www.unicode.org/Public/${version}/ucd/PropertyValueAliases.txt`;

const load = async (source: string): Promise<string> => {
  if (!/^https?:/.test(source)) return readFileSync(source, "utf8");
  const response = await fetch(source);
  if (!response.ok) throw new Error(`${source}: HTTP ${response.status}`);
  return response.text();
};

const confusables = (await load(confusablesSource)).replace(/^﻿/, "");
const aliases = (await load(aliasesSource)).replace(/^﻿/, "");
const sha256 = (text: string) => createHash("sha256").update(text, "utf8").digest("hex");

if (!new RegExp(`^# Version: ${version.replaceAll(".", "\\.")}$`, "m").test(confusables)) {
  throw new Error(`confusables.txt is not version ${version}`);
}
if (!aliases.includes(`PropertyValueAliases-${version}.txt`)) {
  throw new Error(`PropertyValueAliases.txt is not version ${version}`);
}

// `<source> ; <target code points> ; MA # comment`, one code point mapped to
// one or more.
const mappings: Array<readonly [number, ReadonlyArray<number>]> = [];
for (const line of confusables.split("\n")) {
  const data = (line.split("#")[0] ?? "").trim();
  if (data === "") continue;
  const [source, target] = data.split(";").map((field) => field.trim());
  if (source === undefined || target === undefined) throw new Error(`Bad line: ${line}`);
  mappings.push([
    Number.parseInt(source, 16),
    target.split(/\s+/).map((cp) => Number.parseInt(cp, 16)),
  ]);
}
mappings.sort((a, b) => a[0] - b[0]);

// Each entry: the source as a base-36 delta from the previous source, then
// `:` and the target code points in base 36, joined by `.`; entries joined by `,`.
let previous = 0;
const encoded = mappings
  .map(([source, target]) => {
    const entry = `${(source - previous).toString(36)}:${target.map((cp) => cp.toString(36)).join(".")}`;
    previous = source;
    return entry;
  })
  .join(",");

// The four-letter codes of the scripts, without Common, Inherited and Unknown,
// which the checks treat apart.
const scripts = aliases
  .split("\n")
  .map((line) => /^sc\s*;\s*(\w{4})\s*;/.exec(line)?.[1])
  .filter((code): code is string => code !== undefined && !["Zyyy", "Zinh", "Zzzz"].includes(code));

const CHUNK = 96;
const chunks: Array<string> = [];
for (let i = 0; i < encoded.length; i += CHUNK) chunks.push(encoded.slice(i, i + CHUNK));

const target = fileURLToPath(
  new URL("../packages/effect-auth/src/plugins/ConfusablesData.ts", import.meta.url),
);
writeFileSync(
  target,
  `/**
 * GENERATED by \`vpx scripts/generate-confusables.ts ${version}\`; do not edit by hand.
 *
 * Unicode ${version} UTS 39 \`confusables.txt\` (${mappings.length} mappings) and
 * the script codes of the UCD's \`PropertyValueAliases.txt\`.
 *
 * SHA-256 of \`confusables.txt\`: ${sha256(confusables)}
 * SHA-256 of \`PropertyValueAliases.txt\`: ${sha256(aliases)}
 *
 * @internal
 */

/** The Unicode version both files are from. */
export const UNICODE_VERSION = "${version}";

/**
 * The mappings, sorted by source: each a base-36 delta from the previous
 * source, \`:\`, and the target code points in base 36 joined by \`.\`;
 * entries joined by \`,\`.
 */
export const CONFUSABLES = [
${chunks.map((chunk) => `  "${chunk}",`).join("\n")}
].join("");

/** ISO 15924 codes of every script but Common, Inherited and Unknown. */
export const SCRIPTS: ReadonlyArray<string> = [
${scripts.map((code) => `  "${code}",`).join("\n")}
];
`,
);
console.log(`Wrote ${target}: ${mappings.length} mappings, ${scripts.length} scripts`);
