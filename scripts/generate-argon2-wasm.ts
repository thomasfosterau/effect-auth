/**
 * Regenerate `packages/argon2/src/WasmBinary.ts` from the installed
 * `@thomasfosterau/argon2` devDependency (#744).
 *
 * That package embeds its Argon2 wasm as a base64 constant, `WASM_BASE64`, in
 * `dist/index.js` and does not export it. This script reads that file and the
 * package's `package.json`, decodes the constant, and writes the module the
 * adapter compiles: the source version, the SHA-256 of the decoded bytes, and
 * the base64. `packages/argon2/src/Wasm.test.ts` re-derives all three from the
 * installed package and fails if any differs, so a catalog bump without a
 * regeneration fails `test:unit`.
 *
 * Run it after bumping `@thomasfosterau/argon2` in `pnpm-workspace.yaml` and
 * `pnpm install`, once you have checked that release's C ABI (`src/lib.rs`:
 * `alloc`, `dealloc`, `hash`, `last_ptr`, `verify`) is unchanged:
 *
 *   vpx scripts/generate-argon2-wasm.ts
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const packageDir = new URL("../packages/argon2/", import.meta.url);
const sourceDir = new URL("node_modules/@thomasfosterau/argon2/", packageDir);
const SOURCE_FILE = "dist/index.js";
const target = fileURLToPath(new URL("src/WasmBinary.ts", packageDir));

const manifest: unknown = JSON.parse(readFileSync(new URL("package.json", sourceDir), "utf8"));
if (
  typeof manifest !== "object" ||
  manifest === null ||
  !("version" in manifest) ||
  typeof manifest.version !== "string"
) {
  throw new TypeError("@thomasfosterau/argon2's package.json has no version");
}
const version = manifest.version;

const source = readFileSync(new URL(SOURCE_FILE, sourceDir), "utf8");
const base64 = /const WASM_BASE64 = "([A-Za-z0-9+/=]+)";/.exec(source)?.[1];
if (base64 === undefined) {
  throw new TypeError(`No WASM_BASE64 constant in @thomasfosterau/argon2/${SOURCE_FILE}`);
}
const bytes = Buffer.from(base64, "base64");
const sha256 = createHash("sha256").update(bytes).digest("hex");

writeFileSync(
  target,
  `/**
 * GENERATED by \`vpx scripts/generate-argon2-wasm.ts\` from the installed
 * \`@thomasfosterau/argon2\` devDependency; do not edit by hand.
 *
 * The Argon2 WebAssembly binary of \`@thomasfosterau/argon2\`
 * ${version} (\`${SOURCE_FILE}\`, constant \`WASM_BASE64\`, which the package
 * does not export): the RustCrypto \`argon2\` crate built for
 * \`wasm32-unknown-unknown\`, ${bytes.length} bytes, base64-encoded. Embedded
 * as a string rather than imported as a \`.wasm\` asset so every bundler and
 * runtime loads it as plain JavaScript (#744). \`Wasm.test.ts\` checks the
 * version, the SHA-256 and the bytes against the installed package.
 *
 * Licence: \`@thomasfosterau/argon2\` is MIT, Copyright (c) 2026 Thomas
 * Foster. The wasm is compiled from Rust, not from the Argon2 reference C
 * implementation: the RustCrypto \`argon2\` crate and the RustCrypto crates it
 * builds on (\`blake2\`, \`password-hash\`, \`base64ct\`, \`subtle\`) are
 * dual-licensed MIT OR Apache-2.0, used here under MIT.
 *
 * @module argon2/wasm-binary
 * @internal
 */

/** The \`@thomasfosterau/argon2\` release the bytes were copied from. */
export const WASM_SOURCE_VERSION = "${version}";

/** SHA-256 of the decoded bytes, hex. */
export const WASM_SHA256 = "${sha256}";

export const WASM_BASE64: string =
  "${base64}";
`,
);

console.log(`wrote ${target}: @thomasfosterau/argon2 ${version}, sha256 ${sha256}`);
