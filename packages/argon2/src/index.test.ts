import { describe, it, expect } from "vite-plus/test";
import { Array as Arr, Effect } from "effect";
import { ARGON2ID } from "./index.ts";
import * as Argon2 from "./index.ts";
import { Password } from "@thomasfosterau/effect-auth";

const run = <A, E>(effect: Effect.Effect<A, E>): Promise<A> => Effect.runPromise(effect);

/**
 * Cheap explicit costs (256 KiB, one pass) for the tests that check behaviour
 * rather than cost, so they don't depend on how fast the machine is (#270).
 * The profiles stay pinned: by their values below, by the PHC header a
 * default hash carries, and by CostProfiles.test.ts, which checks the costs
 * the hasher hands the KDF without running a derivation.
 */
const cheap = { memoryCost: 256, timeCost: 1, parallelism: 1 } as const;

describe("Argon2.argon2Hasher", () => {
  it("hashes and verifies a password (roundtrip)", async () => {
    const hasher = Argon2.argon2Hasher(cheap);
    const { hash, algorithm } = await run(hasher.hash("correct horse battery staple"));
    expect(algorithm).toBe(ARGON2ID);
    expect(await run(hasher.verify("correct horse battery staple", hash))).toBe(true);
  });

  it("rejects a wrong password", async () => {
    const hasher = Argon2.argon2Hasher(cheap);
    const { hash } = await run(hasher.hash("the-real-password"));
    expect(await run(hasher.verify("not-the-password", hash))).toBe(false);
  });

  it("emits a standard Argon2id PHC string", async () => {
    const { hash } = await run(Argon2.argon2Hasher().hash("phc-shape"));
    expect(hash).toMatch(/^\$argon2id\$v=19\$m=19456,t=2,p=1\$[^$]+\$[^$]+$/);
  });

  it("uses a fresh salt for every hash", async () => {
    const hasher = Argon2.argon2Hasher(cheap);
    const first = await run(hasher.hash("same-password"));
    const second = await run(hasher.hash("same-password"));
    expect(first.hash).not.toBe(second.hash);
    expect(await run(hasher.verify("same-password", first.hash))).toBe(true);
    expect(await run(hasher.verify("same-password", second.hash))).toBe(true);
  });

  it("honours custom cost parameters in the PHC header", async () => {
    const { hash } = await run(
      Argon2.argon2Hasher({ memoryCost: 8192, timeCost: 3, parallelism: 2 }).hash("costs"),
    );
    expect(hash).toContain("$m=8192,t=3,p=2$");
  });

  it("fails on an empty password", async () => {
    const err = await run(Effect.flip(Argon2.argon2Hasher().hash("")));
    expect(err.message).toMatch(/non-empty/);
  });

  it("fails on a password over the anti-DoS ceiling", async () => {
    const err = await run(Effect.flip(Argon2.argon2Hasher().hash("x".repeat(1025))));
    expect(err.message).toMatch(/maximum length/);
  });

  it("verifies an externally produced PHC hash (interop test vector)", async () => {
    // Generated by @node-rs/argon2 with a fixed 16-byte salt.
    const vector =
      "$argon2id$v=19$m=19456,t=2,p=1$MDEyMzQ1Njc4OWFiY2RlZg$3WoR62m00Fza7vJTWPlpjUT9szDdGD07D254dNaM+38";
    const hasher = Argon2.argon2Hasher();
    expect(await run(hasher.verify("interop-vector-password", vector))).toBe(true);
    expect(await run(hasher.verify("wrong", vector))).toBe(false);
  });
});

describe("PHC parameter parsing on verify", () => {
  it("verifies a hash created with cost parameters other than the current config", async () => {
    // Stored under a weak/legacy configuration...
    const legacy = Argon2.argon2Hasher({ memoryCost: 8192, timeCost: 1, parallelism: 1 });
    const { hash } = await run(legacy.hash("legacy-secret"));
    expect(hash).toContain("$m=8192,t=1,p=1$");

    // ...and verified by a hasher configured for the stronger server profile.
    const current = Argon2.argon2Hasher(Argon2.serverProfile);
    expect(await run(current.verify("legacy-secret", hash))).toBe(true);
    expect(await run(current.verify("wrong", hash))).toBe(false);
  });

  it("tolerates a non-canonical parameter order", async () => {
    const { hash } = await run(Argon2.argon2Hasher(cheap).hash("reordered"));
    const reordered = hash.replace(/\$m=(\d+),t=(\d+),p=(\d+)\$/, "$t=$2,p=$3,m=$1$");
    expect(await run(Argon2.argon2Hasher().verify("reordered", reordered))).toBe(true);
  });

  it("fails with a clear error on a malformed hash", async () => {
    const hasher = Argon2.argon2Hasher();
    const cases = [
      "not-a-phc-string",
      "$argon2id$v=19$m=19456,t=2,p=1$only-four-fields",
      "$bcrypt$v=19$m=19456,t=2,p=1$c2FsdHNhbHRzYWx0$aGFzaA",
      "$argon2id$v=16$m=19456,t=2,p=1$c2FsdHNhbHRzYWx0$aGFzaA",
      "$argon2id$v=19$m=abc,t=2,p=1$c2FsdHNhbHRzYWx0$aGFzaA",
    ];
    await Arr.reduce(cases, Promise.resolve(), async (previous, invalid) => {
      await previous;
      const err = await run(Effect.flip(hasher.verify("whatever", invalid)));
      expect(err.message).toMatch(/Invalid Argon2 hash/);
    });
  });

  it("fails on an empty hash", async () => {
    const err = await run(Effect.flip(Argon2.argon2Hasher().verify("password", "")));
    expect(err.message).toMatch(/Hash must be a non-empty string/);
  });
});

describe("cost profiles", () => {
  it("defaults to OWASP's low-memory profile (Workers safe)", () => {
    expect(Argon2.defaultProfile).toEqual({ memoryCost: 19456, timeCost: 2, parallelism: 1 });
  });

  it("exposes a stronger server profile", () => {
    expect(Argon2.serverProfile).toEqual({ memoryCost: 65536, timeCost: 3, parallelism: 1 });
    expect(Argon2.serverProfile.memoryCost).toBeGreaterThan(Argon2.defaultProfile.memoryCost);
    expect(Argon2.serverProfile.timeCost).toBeGreaterThan(Argon2.defaultProfile.timeCost);
  });

  it("resolves partial options against the default profile", () => {
    expect(Argon2.resolveOptions()).toEqual(Argon2.defaultProfile);
    expect(Argon2.resolveOptions({ timeCost: 5 })).toEqual({
      memoryCost: 19456,
      timeCost: 5,
      parallelism: 1,
    });
  });
});

describe("layer", () => {
  it("provides the PasswordHasher service", async () => {
    const result = await run(
      Effect.provide(
        Effect.gen(function* () {
          const hasher = yield* Password.PasswordHasher;
          const { hash, algorithm } = yield* hasher.hash("through-the-layer");
          return { algorithm, verified: yield* hasher.verify("through-the-layer", hash) };
        }),
        Argon2.argon2HasherLayer(cheap),
      ),
    );
    expect(result).toEqual({ algorithm: ARGON2ID, verified: true });
  });
});

/** A `pbkdf2-sha256$iterations$salt$key` hash in core effect-auth's format, via Web Crypto. */
const legacyPbkdf2Hash = async (password: string, iterations: number): Promise<string> => {
  const salt = globalThis.crypto.getRandomValues(new Uint8Array(16));
  const key = await globalThis.crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(password),
    "PBKDF2",
    false,
    ["deriveBits"],
  );
  const bits = await globalThis.crypto.subtle.deriveBits(
    { name: "PBKDF2", salt, iterations, hash: "SHA-256" },
    key,
    32 * 8,
  );
  const hex = (bytes: Uint8Array) =>
    Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
  return `pbkdf2-sha256$${iterations}$${hex(salt)}$${hex(new Uint8Array(bits))}`;
};

describe("multi-algorithm migration", () => {
  it("routes Argon2id and PBKDF2 hashes to the right hasher", async () => {
    const argon2 = Argon2.argon2Hasher(cheap);
    const pbkdf2 = Password.pbkdf2Hasher();
    const verifier = Password.multiAlgorithmVerifier([argon2, pbkdf2]);

    const argonHash = (await run(argon2.hash("shared-secret"))).hash;
    // A stored PBKDF2 hash at a low iteration count: `pbkdf2Hasher` takes no
    // cost option and hashes at 600,000 iterations, but `verify` reads the
    // count from the hash, so this exercises the same routing cheaply (#270).
    const pbkdf2Hash = await legacyPbkdf2Hash("shared-secret", 1000);

    // Each hash verifies through the combined verifier by algorithm detection.
    expect(await run(verifier.verify("shared-secret", argonHash))).toBe(true);
    expect(await run(verifier.verify("shared-secret", pbkdf2Hash))).toBe(true);
    expect(await run(verifier.verify("wrong", argonHash))).toBe(false);
    expect(await run(verifier.verify("wrong", pbkdf2Hash))).toBe(false);
  });
});
