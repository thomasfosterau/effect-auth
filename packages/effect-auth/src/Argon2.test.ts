import { describe, it, expect } from "vite-plus/test";
import { Effect } from "effect";
import { makeMultiAlgorithmVerifier, makePBKDF2Hasher } from "effect-auth";
import { makeArgon2Hasher, ARGON2ID } from "./Argon2.js";

const run = <A, E>(effect: Effect.Effect<A, E>): Promise<A> => Effect.runPromise(effect);

describe("makeArgon2Hasher", () => {
  it("hashes and verifies a password (roundtrip)", async () => {
    const hasher = makeArgon2Hasher();
    const { hash, algorithm } = await run(hasher.hash("correct horse battery staple"));
    expect(algorithm).toBe(ARGON2ID);
    expect(await run(hasher.verify("correct horse battery staple", hash))).toBe(true);
  });

  it("rejects a wrong password", async () => {
    const hasher = makeArgon2Hasher();
    const { hash } = await run(hasher.hash("the-real-password"));
    expect(await run(hasher.verify("not-the-password", hash))).toBe(false);
  });

  it("emits a standard Argon2id PHC string", async () => {
    const { hash } = await run(makeArgon2Hasher().hash("phc-shape"));
    expect(hash).toMatch(/^\$argon2id\$v=19\$m=19456,t=2,p=1\$[^$]+\$[^$]+$/);
  });

  it("honours custom cost parameters in the PHC header", async () => {
    const { hash } = await run(
      makeArgon2Hasher({ memoryCost: 8192, timeCost: 3, parallelism: 2 }).hash("costs"),
    );
    expect(hash).toContain("$m=8192,t=3,p=2$");
  });

  it("fails on an empty password", async () => {
    const err = await run(Effect.flip(makeArgon2Hasher().hash("")));
    expect(err.message).toMatch(/non-empty/);
  });

  it("verifies an externally produced PHC hash (interop test vector)", async () => {
    // Generated by @node-rs/argon2 with a fixed 16-byte salt.
    const vector =
      "$argon2id$v=19$m=19456,t=2,p=1$MDEyMzQ1Njc4OWFiY2RlZg$3WoR62m00Fza7vJTWPlpjUT9szDdGD07D254dNaM+38";
    const hasher = makeArgon2Hasher();
    expect(await run(hasher.verify("interop-vector-password", vector))).toBe(true);
    expect(await run(hasher.verify("wrong", vector))).toBe(false);
  });
});

describe("multi-algorithm migration", () => {
  it("routes Argon2id and PBKDF2 hashes to the right hasher", async () => {
    const argon2 = makeArgon2Hasher();
    const pbkdf2 = makePBKDF2Hasher();
    const verifier = makeMultiAlgorithmVerifier([argon2, pbkdf2]);

    const argonHash = (await run(argon2.hash("shared-secret"))).hash;
    const pbkdf2Hash = (await run(pbkdf2.hash("shared-secret"))).hash;

    // Each hash verifies through the combined verifier by algorithm detection.
    expect(await run(verifier.verify("shared-secret", argonHash))).toBe(true);
    expect(await run(verifier.verify("shared-secret", pbkdf2Hash))).toBe(true);
    expect(await run(verifier.verify("wrong", argonHash))).toBe(false);
    expect(await run(verifier.verify("wrong", pbkdf2Hash))).toBe(false);
  });
});
